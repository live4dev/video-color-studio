"""Host tools for the same Zig Windows target on Windows, macOS and Linux.

Native Windows uses real PE compiler drivers; command files are reviewable companions.
Driver execution requires Windows. No developer tools are installed by this module.
"""

from __future__ import annotations

import hashlib
import importlib.metadata
import os
import platform
import shlex
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = "x86_64-windows-gnu"

_DRIVER_MAIN = r"""
#include <stdlib.h>
#include <stdio.h>

int wmain(void) {
    const wchar_t *tail = GetCommandLineW();
    while (*tail == L' ' || *tail == L'\t') ++tail;
    if (*tail == L'"') {
        ++tail;
        while (*tail && *tail != L'"') ++tail;
        if (*tail) ++tail;
    } else {
        while (*tail && *tail != L' ' && *tail != L'\t') ++tail;
    }
    while (*tail == L' ' || *tail == L'\t') ++tail;
    size_t length = wcslen(zig_path) + wcslen(fixed_arguments) + wcslen(tail) + 6;
    if (length > 32767) {
        fputws(L"Pinned Zig driver command exceeds the Windows command line limit\n", stderr);
        return 126;
    }
    wchar_t *command = calloc(length, sizeof(wchar_t));
    if (!command) return 126;
    swprintf(command, length, L"\"%ls\" %ls %ls", zig_path, fixed_arguments, tail);
    STARTUPINFOW startup = {0};
    PROCESS_INFORMATION process = {0};
    startup.cb = sizeof(startup);
    startup.dwFlags = STARTF_USESTDHANDLES;
    startup.hStdInput = GetStdHandle(STD_INPUT_HANDLE);
    startup.hStdOutput = GetStdHandle(STD_OUTPUT_HANDLE);
    startup.hStdError = GetStdHandle(STD_ERROR_HANDLE);
    if (!CreateProcessW(zig_path, command, NULL, NULL, TRUE, 0, NULL, NULL,
                        &startup, &process)) {
        fwprintf(stderr, L"Cannot start pinned Zig, Windows error %lu\n", GetLastError());
        free(command);
        return 127;
    }
    free(command);
    DWORD exit_code = 126;
    if (WaitForSingleObject(process.hProcess, INFINITE) == WAIT_OBJECT_0)
        GetExitCodeProcess(process.hProcess, &exit_code);
    CloseHandle(process.hThread);
    CloseHandle(process.hProcess);
    return (int)exit_code;
}
"""


def _c_wide(value: str) -> str:
    escaped = []
    for character in value:
        number = ord(character)
        if character in ('"', "\\"):
            escaped.append("\\" + character)
        elif number > 0xFFFF:
            escaped.append(f"\\U{number:08x}")
        elif number > 0x7F:
            escaped.append(f"\\u{number:04x}")
        else:
            escaped.append(character)
    return 'L"' + "".join(escaped) + '"'


def _driver_source(arguments: list[str]) -> str:
    return (
        "/* Generated by windows_native_host.py; first-party MIT source. */\n"
        "#define UNICODE\n#define _UNICODE\n#include <windows.h>\n#include <wchar.h>\n"
        f"static const wchar_t *zig_path = {_c_wide(arguments[0])};\n"
        f"static const wchar_t *fixed_arguments = {_c_wide(' '.join(arguments[1:]))};\n"
        + _DRIVER_MAIN
    )


def _compile_driver(path: Path, arguments: list[str], zig: Path) -> dict:
    source = path.with_suffix(".c")
    source.write_text(_driver_source(arguments), encoding="utf-8")
    command = [
        str(zig),
        "cc",
        "-target",
        TARGET,
        str(source),
        "-municode",
        "-O2",
        "-s",
        "-o",
        str(path),
    ]
    environment = {
        **os.environ,
        "ZIG_LOCAL_CACHE_DIR": str(path.parent / "zig-cache"),
        "ZIG_GLOBAL_CACHE_DIR": str(path.parent / "zig-global-cache"),
    }
    result = subprocess.run(
        command, env=environment, capture_output=True, encoding="utf-8", errors="replace"
    )
    path.with_suffix(".build.log").write_text(result.stdout + result.stderr, encoding="utf-8")
    if result.returncode:
        raise RuntimeError(f"Cannot build Windows Zig driver {path.name}: {result.stderr[-2000:]}")
    data = path.read_bytes()
    offset = int.from_bytes(data[60:64], "little")
    if (
        data[:2] != b"MZ"
        or data[offset : offset + 4] != b"PE\0\0"
        or data[offset + 4 : offset + 6] != b"\x64\x86"
    ):
        raise RuntimeError(f"Pinned Zig driver is not a genuine Windows AMD64 PE: {path}")
    return {
        "source": str(source),
        "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "binary_sha256": hashlib.sha256(data).hexdigest(),
        "command": command,
        "windows_execution": "NOT RUN",
    }


def _package_tool(name: str, windows: bool) -> Path | None:
    try:
        package = importlib.metadata.distribution(name)
    except importlib.metadata.PackageNotFoundError:
        return None
    filename = name + (".exe" if windows else "")
    for entry in package.files or ():
        if entry.name.casefold() == filename.casefold() and "bin" in entry.parts:
            candidate = Path(package.locate_file(entry))
            if candidate.is_file():
                return candidate.resolve()
    return None


def find_host_tool(name: str, *, system: str | None = None) -> Path:
    if name not in ("cmake", "ninja"):
        raise ValueError("Only the build's CMake and Ninja host tools may be resolved")
    system = system or platform.system()
    windows = system == "Windows"
    found = shutil.which(name)
    if found:
        return Path(found).resolve()
    packaged = _package_tool(name, windows)
    if packaged is not None:
        return packaged
    # Retain the existing macOS isolated-build cache fallback; never search it on Windows.
    if system == "Darwin":
        pattern = f"*/{name}/data/bin/{name}"
        cached = sorted((ROOT / "build/opencv-image-only/cache/archive-v0").glob(pattern))
        if cached:
            return cached[0].resolve()
    raise RuntimeError(
        f"Host {name} is required. Install CMake and Ninja into this build environment "
        "(for example: python -m pip install cmake ninja), or put their executables on PATH. "
        "The application itself does not need these developer tools."
    )


def _cmd_argument(value: str) -> str:
    if any(character in value for character in ('"', "\r", "\n", "\0")):
        raise ValueError("A fixed Windows compiler-wrapper argument contains an invalid character")
    # Always quote shell metacharacters, including paths without whitespace. Percent
    # must be doubled inside a command file even within a quoted argument.
    return '"' + value.replace("%", "%%") + '"'


def _write_wrapper(path: Path, arguments: list[str], *, windows: bool) -> str:
    if windows:
        command = " ".join(_cmd_argument(argument) for argument in arguments)
        content = (
            "@echo off\r\nsetlocal DisableDelayedExpansion\r\n"
            f"{command} %*\r\nexit /b %errorlevel%\r\n"
        )
    else:
        content = "#!/bin/sh\nexec " + shlex.join(arguments) + ' "$@"\n'
    path.write_bytes(content.encode("utf-8"))
    if not windows:
        path.chmod(0o755)
    return str(path)


def host_plan(work: Path, zig: Path) -> dict:
    """Produce JSON-safe wrapper paths and native build-tool/environment choices."""
    system = platform.system()
    if system not in ("Windows", "Darwin", "Linux"):
        raise RuntimeError(f"Unsupported OpenCV build host: {system}")
    windows = system == "Windows"
    work, zig = Path(work).expanduser().resolve(), Path(zig).expanduser().resolve()
    if not zig.is_file():
        raise FileNotFoundError(f"The pinned host Zig executable does not exist: {zig}")
    cmake = find_host_tool("cmake", system=system)
    ninja = find_host_tool("ninja", system=system) if windows else None
    wrappers = work / "wrappers"
    wrappers.mkdir(parents=True, exist_ok=True)
    commands = {
        "cc": [str(zig), "cc", "-target", TARGET],
        "cxx": [str(zig), "c++", "-target", TARGET],
        "ar": [str(zig), "ar"],
        "ranlib": [str(zig), "ranlib"],
        "rc": [str(zig), "rc"],
    }
    command_wrappers = {
        key: _write_wrapper(
            wrappers / (f"zig-{key}" + (".cmd" if windows else "")),
            arguments,
            windows=windows,
        )
        for key, arguments in commands.items()
    }
    paths = dict(command_wrappers)
    drivers = {}
    if windows:
        # Ninja's Windows process launcher directly uses CreateProcess, which cannot
        # execute .cmd files. Genuine PE drivers work for compile, RC and AR rules alike.
        for key, arguments in commands.items():
            path = wrappers / f"zig-{key}.exe"
            drivers[key] = _compile_driver(path, arguments, zig)
            paths[key] = str(path)
    environment = {}
    if ninja is not None:
        environment["PATH"] = str(ninja.parent) + ";" + os.environ.get("PATH", "")
    return {
        **paths,
        "generator": "Ninja" if windows else "Unix Makefiles",
        "cmake": [str(cmake)],
        "ninja": str(ninja) if ninja is not None else None,
        "environment": environment,
        "command_wrappers": command_wrappers,
        "drivers": drivers,
        "host_system": system,
        "target": TARGET,
        "windows_wrapper_execution": "NOT RUN" if windows else "not applicable",
    }
